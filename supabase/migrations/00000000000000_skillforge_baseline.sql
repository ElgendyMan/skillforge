-- Helper functions used by RLS. Keep them non-public in the destination project.
create or replace function private.current_role() returns public.app_role language sql stable security definer set search_path = public as $$
  select role from public.profiles where id = auth.uid()
$$;
create or replace function private.is_company_member(target_company_id bigint) returns boolean language sql stable security definer set search_path = public as $$
  select exists(select 1 from public.company_members where company_id = target_company_id and user_id = auth.uid())
$$;

