create policy profiles_self_read on public.profiles for select using (id = auth.uid() or private.current_role() = 'supervisor');
create policy companies_public_read on public.companies for select using (true);
create policy company_members_scoped_read on public.company_members for select using (user_id = auth.uid() or private.current_role() = 'supervisor');
create policy published_tests_read on public.tests for select using (status = 'published' or private.is_company_member(company_id) or private.current_role() = 'supervisor');
create policy candidate_attempts_read on public.test_attempts for select using (candidate_id = auth.uid() or private.is_company_member((select company_id from public.tests where id = test_id)) or private.current_role() = 'supervisor');
create policy candidate_answers_read on public.attempt_answers for select using ((select candidate_id from public.test_attempts where id = attempt_id) = auth.uid() or private.current_role() = 'supervisor' or private.is_company_member((select company_id from public.tests where id = (select test_id from public.test_attempts where id = attempt_id))));
create policy candidate_files_read on public.file_assets for select using (owner_user_id = auth.uid() or private.current_role() = 'supervisor' or private.is_company_member(company_id));
create policy candidate_notifications_read on public.notifications for select using (user_id = auth.uid() or private.current_role() = 'supervisor');
create policy candidate_appeals_read on public.appeals for select using (candidate_id = auth.uid() or private.current_role() = 'supervisor');
create policy candidate_accommodations_read on public.accommodations for select using (candidate_id = auth.uid() or private.current_role() = 'supervisor');
create policy reviews_scoped_read on public.reviews for select using (reviewer_user_id = auth.uid() or private.current_role() = 'supervisor' or exists(select 1 from public.test_attempts a join public.tests t on t.id=a.test_id where a.id=attempt_id and private.is_company_member(t.company_id)));
create policy audit_supervisor_read on public.audit_logs for select using (private.current_role() = 'supervisor');

