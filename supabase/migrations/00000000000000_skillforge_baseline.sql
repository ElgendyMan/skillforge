create schema if not exists private;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text,
  email text,
  role public.app_role not null default 'candidate',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists public.companies (
  id bigint generated by default as identity primary key,
  name text not null, slug text not null unique, description text, website text, industry text,
  logo_key text, created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.company_members (
  id bigint generated by default as identity primary key,
  company_id bigint not null references public.companies(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  member_role text not null default 'owner' check (member_role in ('owner','reviewer')),
  created_at timestamptz not null default now(), unique(company_id,user_id)
);
create table if not exists public.tests (
  id bigint generated by default as identity primary key,
  company_id bigint not null references public.companies(id) on delete cascade,
  title text not null, job_title text, summary text not null, field text not null,
  level text not null check(level in ('junior','mid','senior')), duration_minutes integer not null check(duration_minutes > 0),
  status public.test_status not null default 'draft', proctoring_mode text not null default 'optional' check(proctoring_mode in ('none','optional','required')),
  attempts_allowed integer not null default 1 check(attempts_allowed > 0), version integer not null default 1,
  immutable boolean not null default false, published_at timestamptz, created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.test_sections (
  id bigint generated by default as identity primary key, test_id bigint not null references public.tests(id) on delete cascade,
  title text not null, instructions text, sort_order integer not null
);
create table if not exists public.test_questions (
  id bigint generated by default as identity primary key, section_id bigint not null references public.test_sections(id) on delete cascade,
  type public.question_type not null, prompt text not null, guidance text, points integer not null default 10,
  options jsonb, correct_answers jsonb, evaluation_guide text, starter_code text, supported_languages jsonb,
  sort_order integer not null, version integer not null default 1, is_retired boolean not null default false
);
create table if not exists public.test_attempts (
  id bigint generated by default as identity primary key, test_id bigint not null references public.tests(id), candidate_id uuid not null references public.profiles(id),
  state text not null default 'in_progress' check(state in ('in_progress','paused_for_technical_issue','submitted','expired','under_review')),
  application_status public.application_status not null default 'under review', started_at timestamptz not null default now(), submitted_at timestamptz,
  expires_at timestamptz not null, grace_ends_at timestamptz, technical_issue_reason text, test_version integer not null default 1,
  auto_score integer, reviewer_score integer, priority_score integer not null default 0, integrity_flags integer not null default 0,
  updated_at timestamptz not null default now(), unique(test_id,candidate_id)
);
create table if not exists public.attempt_section_snapshots (
  id bigint generated by default as identity primary key, attempt_id bigint not null references public.test_attempts(id) on delete cascade,
  original_section_id bigint not null, title text not null, instructions text, sort_order integer not null
);
create table if not exists public.attempt_question_snapshots (
  id bigint generated by default as identity primary key, attempt_id bigint not null references public.test_attempts(id) on delete cascade,
  original_question_id bigint not null, section_snapshot_id bigint not null references public.attempt_section_snapshots(id) on delete cascade,
  type public.question_type not null, prompt text not null, guidance text, points integer not null,
  options jsonb, correct_answers jsonb, evaluation_guide text, starter_code text, supported_languages jsonb, sort_order integer not null
);
create table if not exists public.attempt_answers (
  id bigint generated by default as identity primary key, attempt_id bigint not null references public.test_attempts(id) on delete cascade,
  question_id bigint not null, text_answer text, selected_option_ids jsonb, code_answer text, language text, file_asset_id bigint,
  saved_at timestamptz not null default now(), unique(attempt_id,question_id)
);
create table if not exists public.file_assets (
  id bigint generated by default as identity primary key, owner_user_id uuid not null references public.profiles(id), company_id bigint references public.companies(id),
  attempt_id bigint references public.test_attempts(id), category text not null, storage_key text not null unique, original_name text not null,
  mime_type text not null, byte_size integer not null, sha256 text, security_status public.asset_security_status not null default 'pending',
  expires_at timestamptz, created_at timestamptz not null default now()
);
create table if not exists public.reviews (
  id bigint generated by default as identity primary key, attempt_id bigint not null unique references public.test_attempts(id),
  reviewer_user_id uuid not null references public.profiles(id), score integer not null check(score between 0 and 100), decision public.application_status not null,
  review_status text not null default 'completed', rationale text, evidence_reference text, notes text, created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.code_review_comments (
  id bigint generated by default as identity primary key, attempt_id bigint not null references public.test_attempts(id) on delete cascade,
  attempt_answer_id bigint not null references public.attempt_answers(id) on delete cascade, reviewer_user_id uuid not null references public.profiles(id),
  line_number integer not null check(line_number > 0), body text not null, created_at timestamptz not null default now()
);
create table if not exists public.candidate_annotations (
  id bigint generated by default as identity primary key, company_id bigint not null references public.companies(id) on delete cascade,
  candidate_id uuid not null references public.profiles(id) on delete cascade, note text not null, tags jsonb not null default '[]',
  updated_by_user_id uuid not null references public.profiles(id), created_at timestamptz not null default now(), updated_at timestamptz not null default now(), unique(company_id,candidate_id)
);
create table if not exists public.notifications (
  id bigint generated by default as identity primary key, user_id uuid not null references public.profiles(id) on delete cascade,
  type text not null, notification_key text unique, title text not null, content text not null, read_at timestamptz,
  email_status text not null default 'not_configured', created_at timestamptz not null default now()
);
create table if not exists public.appeals (
  id bigint generated by default as identity primary key, attempt_id bigint not null references public.test_attempts(id) on delete cascade,
  candidate_id uuid not null references public.profiles(id), reason text not null check(char_length(reason) between 20 and 4000),
  status text not null default 'open', resolution text, created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.accommodations (
  id bigint generated by default as identity primary key, candidate_id uuid not null references public.profiles(id), attempt_id bigint references public.test_attempts(id),
  type text not null, details text, status text not null default 'requested', created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key, actor_user_id uuid references public.profiles(id), action text not null,
  entity_type text not null, entity_id bigint, detail text, created_at timestamptz not null default now()
);

